    public static List<String> ids() { return POOL.stream().map(Entry::item).toList(); }
    public static int size() { return POOL.size(); }
    /** {@code n} distinct candidates with a random amount inside each item's usual range. */
    public static List<Candidate> draw(int n) { return draw(n, ThreadLocalRandom.current()); }
    public static List<Candidate> draw(int n, Random random) {
        List<Entry> left = new ArrayList<>(POOL), picked = new ArrayList<>();
        while (picked.size() < Math.min(n, POOL.size())) picked.add(left.remove(random.nextInt(left.size())));
        return picked.stream().map(entry -> new Candidate(entry.item(), entry.min() + random.nextInt(entry.max() - entry.min() + 1))).toList();
    }
