DRINKS = {"ale": ALE, "kvass": KVASS, "wine": WINE, "mead": MEAD}


def icon(art):
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), [len(r) for r in rows]
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != ".":
                px[x, y] = COLORS[ch] + (255,)
    return img


def main():
    tex = os.path.join(ASSETS, "textures", "item")
    models = os.path.join(ASSETS, "models", "item")
    os.makedirs(tex, exist_ok=True)
    for name, art in DRINKS.items():
        icon(art).save(os.path.join(tex, "bar_" + name + ".png"))
        with open(os.path.join(models, "bar_" + name + ".json"), "w", encoding="utf-8") as f:
            json.dump({"parent": "minecraft:item/generated", "textures": {"layer0": "mobtalk:item/bar_" + name}}, f, indent=2)
            f.write("\n")
    print("drinks: 4 icons written")


if __name__ == "__main__":
    main()
