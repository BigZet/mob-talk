def width(s, scale=1):
    return sum((len(G[c][0]) + 1) * scale for c in s) - scale if s else 0


def text(img, x, y, s, colour, scale=1):
    px = img.load()
    c4 = colour + (255,) if len(colour) == 3 else colour
    for ch in s:
        g = G[ch]
        for gy, row in enumerate(g):
            for gx, bit in enumerate(row):
                if bit == '1':
                    for dy in range(scale):
                        for dx in range(scale):
                            X, Y = x + gx * scale + dx, y + gy * scale + dy
                            if 0 <= X < img.width and 0 <= Y < img.height:
                                px[X, Y] = c4
        x += (len(g[0]) + 1) * scale
    return x


def centred(img, cx, y, s, colour, scale=1):
    return text(img, cx - width(s, scale) // 2, y, s, colour, scale)
