"""Cuts labelled 16³ cubes out of the player's own saves, read-only, without running the game.

For every world folder: (1) scans all overworld region files in parallel for built blocks (planks, masonry, glass, doors,
fences, rails, torches, beds, chests, ...), for the vanilla structure starts the world recorded and for monster spawners;
(2) drops built blocks inside any vanilla structure piece (villages, mineshafts, ...) and around spawners (dungeons);
(3) groups the rest into builds (4-block bins, 26-neighbourhood), cuts cubes at places a creature could stand inside each build
and labels them by rule (rules.py), 'unknown' when no rule is sure; (4) also cuts cubes inside the recorded vanilla pieces,
dungeons and natural background, as real-world counterparts of the harvested classes.

    python saves.py --saves "%APPDATA%/PrismLauncher/instances/1.21.1-fabric-dev/minecraft/saves" --out %LOCALAPPDATA%/MobTalk/voxel/saves
"""
import argparse, collections, json, os, random, re, time
from multiprocessing import Pool
import numpy as np
import anvil
from dataset import BlockTable, MAT, FAM, write_v2, DATA
import rules

_TABLE = None
_ART_FAMILIES = {FAM[f] for f in ('PLANKS', 'MASONRY', 'GLASS', 'WOOL', 'BED', 'STORAGE', 'WORKSTATION', 'LIGHT', 'RAIL', 'METAL', 'DECORATION',
                                   'REDSTONE', 'COLORED')}
_ART_MATERIALS = {MAT[m] for m in ('FENCE', 'DOOR_OPEN', 'DOOR_CLOSED', 'FARMLAND')}


def _table():
    global _TABLE
    if _TABLE is None: _TABLE = BlockTable()
    return _TABLE


# Generated by nature often enough to make false builds: lush caves, boulders in old taiga.
NATURALISH = {'minecraft:moss_carpet', 'minecraft:mossy_cobblestone', 'minecraft:chain', 'minecraft:sculk_sensor'}


def built(name):
    """Whether a block is something a player places rather than terrain the world generator makes."""
    if name.endswith('terracotta') and 'glazed' not in name: return False  # badlands are made of it
    if name in NATURALISH: return False
    t = _table()
    return t.family_of(name) in _ART_FAMILIES or t.material.get(name, 0) in _ART_MATERIALS


def scan_region(path):
    """Built blocks (x, y, z, name id), spawners, structure starts of one region file."""
    try:
        region = anvil.Region(path)
    except Exception as e:
        return dict(points=np.zeros((0, 4), np.int32), names=[], spawners=[], starts=[], error=str(e))
    names, name_ids, flags = [], {}, {}
    pts, spawners, starts = [], [], []
    for lx, lz in region.chunk_coords():
        try:
            chunk = region.chunk(lx, lz)
        except Exception:
            continue
        if chunk is None: continue
        # A start is recorded early in generation: its own chunk may never have been finished while its pieces were.
        starts.extend(anvil.structure_starts(chunk))
        if chunk.get('Status') not in ('minecraft:full', 'full'): continue
        cx, cz = region.rx * 32 + lx, region.rz * 32 + lz
        for s in chunk.get('sections') or []:
            states = s.get('block_states')
            if not states: continue
            pal = [p.get('Name', 'minecraft:air') for p in states.get('palette', [])]
            hit = [flags.setdefault(n, built(n)) for n in pal]
            spawn = [n == 'minecraft:spawner' for n in pal]
            if not any(hit) and not any(spawn): continue
            decoded = anvil.section_blocks(s)
            if decoded is None: continue
            _, idx = decoded
            sy = int(s['Y'])
            for i, n in enumerate(pal):
                if not hit[i] and not spawn[i]: continue
                ys, zs, xs = np.nonzero(idx == i)
                if not len(ys): continue
                if spawn[i]:
                    spawners += [(cx * 16 + int(x), sy * 16 + int(y), cz * 16 + int(z)) for x, y, z in zip(xs, ys, zs)]
                    continue
                nid = name_ids.setdefault(n, len(names))
                if nid == len(names): names.append(n)
                pts.append(np.stack([xs + cx * 16, ys + sy * 16, zs + cz * 16, np.full(len(xs), nid)], axis=1).astype(np.int32))
    points = np.concatenate(pts) if pts else np.zeros((0, 4), np.int32)
    return dict(points=points, names=names, spawners=spawners, starts=starts)


def scan_world(folder, pool):
    region_dir = os.path.join(folder, 'region')
    paths = [os.path.join(region_dir, f) for f in os.listdir(region_dir) if f.endswith('.mca')] if os.path.isdir(region_dir) else []
    names, ids, chunks, spawners, starts = [], {}, [], [], []
    for r in pool.imap_unordered(scan_region, paths):
        remap = np.array([ids.setdefault(n, len(ids)) for n in r['names']] or [0], dtype=np.int32)
        for n in r['names']:
            if len(names) < len(ids): names.append(n)
        p = r['points']
        if len(p): p = p.copy(); p[:, 3] = remap[p[:, 3]]; chunks.append(p)
        spawners += r['spawners']; starts += r['starts']
    names = [n for n, _ in sorted(ids.items(), key=lambda kv: kv[1])]
    points = np.concatenate(chunks) if chunks else np.zeros((0, 4), np.int32)
    return points, names, spawners, starts


def outside(points, boxes, margin=2):
    """Mask of points not inside any box (minX, minY, minZ, maxX, maxY, maxZ), boxes grown by margin."""
    keep = np.ones(len(points), dtype=bool)
    if not len(points) or not boxes: return keep
    by_chunk = collections.defaultdict(list)
    cxs, czs = points[:, 0] >> 4, points[:, 2] >> 4
    order = np.lexsort((czs, cxs))
    keys = cxs[order].astype(np.int64) * 1_000_003 + czs[order]
    uniq, first = np.unique(keys, return_index=True)
    bounds = dict(zip(uniq.tolist(), zip(first.tolist(), list(first[1:]) + [len(order)])))
    for b in boxes:
        x0, y0, z0, x1, y1, z1 = b[0] - margin, b[1] - margin, b[2] - margin, b[3] + margin, b[4] + margin, b[5] + margin
        for cx in range(x0 >> 4, (x1 >> 4) + 1):
            for cz in range(z0 >> 4, (z1 >> 4) + 1):
                k = cx * 1_000_003 + cz
                if k not in bounds: continue
                a, e = bounds[k]
                sel = order[a:e]
                p = points[sel]
                inside = (p[:, 0] >= x0) & (p[:, 0] <= x1) & (p[:, 1] >= y0) & (p[:, 1] <= y1) & (p[:, 2] >= z0) & (p[:, 2] <= z1)
                keep[sel[inside]] = False
    return keep


def components(points):
    """Builds: connected groups of 4-block bins holding built blocks. Returns a list of point-index arrays."""
    bins = points[:, :3] >> 2
    keys, inverse = np.unique(bins, axis=0, return_inverse=True)
    inverse = inverse.reshape(-1)
    index = {tuple(k): i for i, k in enumerate(keys.tolist())}
    parent = list(range(len(keys)))
    def find(i):
        while parent[i] != i: parent[i] = parent[parent[i]]; i = parent[i]
        return i
    for i, (x, y, z) in enumerate(keys.tolist()):
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                for dz in (-1, 0, 1):
                    j = index.get((x + dx, y + dy, z + dz))
                    if j is not None and j > i:
                        a, b = find(i), find(j)
                        if a != b: parent[a] = b
    roots = np.array([find(i) for i in range(len(keys))])
    groups = collections.defaultdict(list)
    for pi, b in enumerate(inverse.tolist()): groups[roots[b]].append(pi)
    return [np.array(v) for v in groups.values()]


class Cutter:
    """Cuts cubes from a world and keeps the dataset arrays."""
    def __init__(self, world, save):
        self.world, self.save, self.table = world, save, _table()
        self.cubes, self.blocks, self.meta = [], [], []
        self.taken = set()

    def arrays(self, x0, y0, z0, sx, sy, sz):
        pal, idx = self.world.box(x0, y0, z0, sx, sy, sz)
        if pal is None: return None
        t = self.table
        mat_lut = np.array([t.material_of(n, p) for n, p in pal], dtype=np.uint8)
        fam_lut = np.array([t.family_of(n) for n, _ in pal], dtype=np.uint8)
        return pal, idx, mat_lut[idx], fam_lut[idx]

    def standable(self, mat):
        p = rules.PASSABLE[mat]
        ok = np.zeros_like(p)
        ok[:, 1:-1, :] = p[:, 1:-1, :] & p[:, 2:, :] & ~p[:, :-2, :]
        return ok

    def feet_near(self, x, y, z, reach=4):
        """A standable cell near (x, y, z), closest first, or None."""
        a = self.arrays(x - reach, y - reach, z - reach, 2 * reach + 1, 2 * reach + 1, 2 * reach + 1)
        if a is None: return None
        ok = self.standable(a[2])
        cells = np.argwhere(ok)
        if not len(cells): return None
        d = ((cells - reach) ** 2).sum(axis=1)
        c = cells[int(np.argmin(d))]
        return x - reach + int(c[0]), y - reach + int(c[1]), z - reach + int(c[2])

    def cut(self, feet, meta, rule=True, tower=False):
        x, y, z = feet
        if (x, y, z) in self.taken: return None
        a = self.arrays(x - 8, y - 7, z - 8, 16, 16, 16)
        if a is None: return None
        pal, idx, mat, fam = a
        names = [n for n, _ in pal]
        name_pal, name_idx = [], {}
        remap = np.array([name_idx.setdefault(n, len(name_idx)) for n in names], dtype=np.uint16)
        name_pal = [n for n, _ in sorted(name_idx.items(), key=lambda kv: kv[1])]
        self.taken.add((x, y, z))
        m = dict(src='save', save=self.save, pos=[x, y, z], biome=self.world.biome(x, y, z), palette=name_pal, **meta)
        if rule:
            names_arr = np.array(names, dtype=object)[idx]
            win, fired, f = rules.label(mat, fam, names_arr, tower=tower)
            m['rule'] = win; m['fired'] = fired
            m['features'] = {k: v for k, v in f.items() if k in ('volume', 'open', 'roof', 'walls', 'underground', 'artificial')}
            if win != 'unknown': m['fine'] = win
        self.cubes.append(mat); self.blocks.append(remap[idx]); self.meta.append(m)
        return m


def farthest(points, k, rng):
    """k spread-out representatives of a point set (farthest-point sampling)."""
    chosen = [int(rng.integers(len(points)))]
    d = ((points - points[chosen[0]]) ** 2).sum(axis=1)
    while len(chosen) < min(k, len(points)):
        i = int(np.argmax(d))
        if d[i] == 0: break
        chosen.append(i)
        d = np.minimum(d, ((points - points[i]) ** 2).sum(axis=1))
    return chosen


MARKERS = ('/villagers', '/animals', '/mobs', 'village/common/')


def process(folder, save, pool, out, rng, args):
    started = time.time()
    points, names, spawners, starts = scan_world(folder, pool)
    boxes = [c['bb'] for s in starts for c in s['children']]
    keep = outside(points, boxes)
    if spawners:
        sp = np.array(spawners)
        keep &= outside(points, [[x - 6, y - 4, z - 6, x + 6, y + 4, z + 6] for x, y, z in spawners], margin=0)
    built_pts = points[keep]
    world = anvil.World(folder)
    cutter = Cutter(world, save)
    stats = collections.Counter()
    builds = []
    if len(built_pts):
        for comp in components(built_pts):
            p = built_pts[comp]
            distinct = len(set(p[:, 3].tolist()))
            lo, hi = p[:, :3].min(axis=0), p[:, :3].max(axis=0)
            line = sorted((hi - lo + 1).tolist())
            # One kind of block is a build only as a straight line (a pole, a wall top); a blob of cobblestone is lava meeting water.
            if len(p) < 12 or distinct < 2 and not (line[0] == 1 and line[1] <= 2 and line[2] >= 8): continue
            builds.append(p)
    builds.sort(key=len, reverse=True)
    for p in builds[:args.max_builds]:
        lo, hi = p[:, :3].min(axis=0), p[:, :3].max(axis=0)
        ext = hi - lo + 1
        tower = ext[0] <= 9 and ext[2] <= 9 and ext[1] >= 12
        k = min(args.per_build, 1 + len(p) // 60)
        bins = np.unique(p[:, :3] >> 2, axis=0) * 4 + 2
        for i in farthest(bins, k, rng):
            feet = cutter.feet_near(*bins[i].tolist())
            if feet is None: stats['no-feet'] += 1; continue
            m = cutter.cut(feet, dict(kind='build', build_size=int(len(p)), build_extent=ext.tolist()), tower=tower)
            if m: stats['build:' + m['rule']] += 1
    # Vanilla pieces the world recorded: real-world counterparts of the harvested ones.
    rng.shuffle(starts)
    for s in starts[:args.max_starts]:
        pieces = [c for c in s['children'] if c['template'] is not None and not any(mk in (c['template'] or '') for mk in MARKERS)]
        rng.shuffle(pieces)
        for c in pieces[:args.per_start]:
            bb = c['bb']
            cx, cy, cz = (bb[0] + bb[3]) // 2, (bb[1] + bb[4]) // 2, (bb[2] + bb[5]) // 2
            feet = cutter.feet_near(cx, max(cy, bb[1] + 1), cz, reach=min(6, max(2, (bb[3] - bb[0]) // 2)))
            if feet is None or not (bb[0] - 1 <= feet[0] <= bb[3] + 1 and bb[2] - 1 <= feet[2] <= bb[5] + 1): continue
            m = cutter.cut(feet, dict(kind='structure', structure=s['id'], piece_type=c['id'], template=c['template'] or ''), rule=False)
            if m: stats['vanilla:' + s['id'].split(':')[-1]] += 1
    for x, y, z in spawners[:args.max_dungeons]:
        if not outside(np.array([[x, y, z, 0]]), boxes)[0]: continue
        feet = cutter.feet_near(x + 2, y, z)
        if feet is None: continue
        if cutter.cut(feet, dict(kind='dungeon', fine='dungeon'), rule=False): stats['dungeon'] += 1
    # Natural background, away from builds and structures.
    regions = [f for f in os.listdir(os.path.join(folder, 'region')) if f.endswith('.mca')]
    near = set(map(tuple, (points[:, [0, 2]] >> 4).tolist())) if len(points) else set()
    tries = 0
    while stats['background'] < args.background and tries < args.background * 10 and regions:
        tries += 1
        rname = regions[rng.integers(len(regions))].split('.')
        x = int(rname[1]) * 512 + int(rng.integers(512)); z = int(rname[2]) * 512 + int(rng.integers(512))
        if (x >> 4, z >> 4) in near: continue
        h = world.height(x, z)
        if h is None: continue
        cave = rng.random() < 0.35
        if cave:
            y = int(rng.integers(-50, max(-49, h - 12)))
            feet = cutter.feet_near(x, y, z, reach=6)
            relief = 'cave'
        else:
            feet = (x, h, z); relief = 'surface'
            a = cutter.arrays(x, h - 1, z, 1, 1, 1)
            if a is None: continue
            if a[2][0, 0, 0] == MAT['WATER']: relief = 'water'
        if feet is None: continue
        if not outside(np.array([[feet[0], feet[1], feet[2], 0]]), boxes, margin=16)[0]: continue
        m = cutter.cut(feet, dict(kind='background', relief=relief), rule=False)
        if m: stats['background'] += 1
    base = os.path.join(out, re.sub(r'[^\w\- ]', '_', save))
    if cutter.cubes:
        write_v2(base, np.stack(cutter.cubes), np.stack(cutter.blocks), cutter.meta)
    print(f'{save}: {len(points)} built cells, {len(starts)} starts, {len(spawners)} spawners, {len(builds)} builds, {len(cutter.cubes)} cubes '
          f'in {time.time() - started:.0f}s: {dict(stats)}', flush=True)
    return save, dict(stats), len(builds)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--saves', default=os.path.join(os.environ.get('APPDATA', ''), 'PrismLauncher', 'instances', '1.21.1-fabric-dev', 'minecraft', 'saves'))
    ap.add_argument('--out', default=os.path.join(DATA, 'saves'))
    ap.add_argument('--only', nargs='*'); ap.add_argument('--max-builds', type=int, default=400); ap.add_argument('--per-build', type=int, default=12)
    ap.add_argument('--max-starts', type=int, default=80); ap.add_argument('--per-start', type=int, default=3)
    ap.add_argument('--max-dungeons', type=int, default=20); ap.add_argument('--background', type=int, default=60)
    ap.add_argument('--workers', type=int, default=8)
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    rng = np.random.default_rng(7)
    worlds = sorted(w for w in os.listdir(args.saves) if os.path.isdir(os.path.join(args.saves, w, 'region')) and not w.startswith('mobtalk-'))
    if args.only: worlds = [w for w in worlds if w in args.only]
    report = {}
    with Pool(args.workers) as pool:
        for w in worlds:
            save, stats, builds = process(os.path.join(args.saves, w), w, pool, args.out, rng, args)
            report[save] = dict(stats=stats, builds=builds)
    json.dump(report, open(os.path.join(args.out, 'report.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)


if __name__ == '__main__':
    main()
